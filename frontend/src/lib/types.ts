export type Status = "queued" | "running" | "completed" | "failed";
export type Finding = {
  code: string;
  category: string;
  severity: "critical" | "high" | "medium" | "low";
  title: string;
  description: string;
  evidence: string;
  recommendation: string;
  source: "measurement" | "ai_judgment";
};
export type Score = { score: number | null; method: string; source: string };
export type Analysis = {
  id: string;
  url: string;
  normalized_url: string;
  domain: string;
  title: string;
  status: Status;
  overall_score: number | null;
  scores: Record<string, Score>;
  metrics: { desktop?: Record<string, unknown>; mobile?: Record<string, unknown>; score_deduction_points?: Record<string, number>; [key: string]: unknown };
  lighthouse: { performance?: number | null; accessibility?: number | null; best_practices?: number | null; seo?: number | null; metrics?: Record<string, { value?: number; display?: string; score?: number } | null>; available?: boolean; error?: string };
  findings: Finding[];
  positives: string[];
  recommendations: { priority: string; title: string; rationale: string; action: string }[];
  summary: string;
  ai_status: string;
  is_favorite: boolean;
  screenshot_available: boolean;
  error_code: string;
  error_message: string;
  created_at: string;
  started_at: string | null;
  completed_at: string | null;
};
export type Paginated<T> = { count: number; next: string | null; previous: string | null; results: T[] };
export type User = { id: number; email: string; display_name: string; role: "user" | "admin"; date_joined: string };
export type ApiErrorBody = { error?: { detail?: unknown }; detail?: unknown; [key: string]: unknown };
